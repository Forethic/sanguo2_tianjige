    /// <summary>
    /// 丰富技能说明与实战数值明细
    /// </summary>
    public static (string DamageDetail, string Description) Enrich(string skillName, string defaultDescription, string defaultDetail)
    {
        if (string.IsNullOrWhiteSpace(skillName)) return (defaultDetail, defaultDescription);

        var clean = skillName.Trim();
        if (Details.TryGetValue(clean, out var pair))
        {
            return pair;
        }

        // 尝试模糊匹配 (如包含 伏兵班阵)
        foreach (var (key, val) in Details)
        {
            if (clean.Contains(key) || key.Contains(clean))
            {
                return val;
            }
        }

        return (defaultDetail, defaultDescription);
    }
